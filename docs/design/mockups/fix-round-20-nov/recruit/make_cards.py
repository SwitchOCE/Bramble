#!/usr/bin/env python3
"""Write cards.js for these mock-ups from the build's own content (src/content/*/units.json).

Run from the repo root: python3 docs/design/mockups/fix-round-20-nov/recruit/make_cards.py
Text placeholders are filled with the card's own effect numbers, as the game does.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
OUT = Path(__file__).with_name("cards.js")
cards = {}
for tribe in ["badger", "mouse", "pigeon", "locust", "thorn"]:
    for c in json.loads((ROOT / "src/content" / tribe / "units.json").read_text())["cards"]:
        vals = {}
        for e in c.get("effects", []):
            for k, v in e.items():
                if isinstance(v, (int, float)) and k not in vals:
                    vals[k] = v
        text = re.sub(r"\{(\w+)\}", lambda m: str(vals.get(m.group(1), 1)), c.get("text", ""))
        cards[c["id"]] = {
            "id": c["id"], "name": c["name"], "tier": c["tier"], "attack": c["attack"], "health": c["health"],
            "types": c.get("types", []), "tribe": tribe, "text": text,
        }
OUT.write_text("// Generated by make_cards.py from src/content/*/units.json. Do not edit by hand.\nwindow.BR_CARDS=" + json.dumps(cards) + ";\n")
print(f"{len(cards)} cards -> {OUT}")
