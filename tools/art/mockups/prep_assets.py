"""Builds the mock-up's card assets from the art recipe's pictures and the locked frames.

    python tools/art/mockups/prep_assets.py <art root> [--window <window.json>]

<art root> holds run folders of 1024 x 1536 Codex pictures (fighters1, fighters2, awkward1, awkward2),
as made by the card art recipe. Each picture is moved into card space with the recipe's one fixed crop
(the card at 1.44x on the canvas, top-left at (108.8, 48)) and saved at half card size, 560 x 1000, as
<subject>-<run>.jpg. Nothing is scaled or nudged by hand. The page clips the art to the recipe's art
polygon, so it is not masked here.

The six frames from frame-lab/final are saved at 560 x 1000 as WebP with their transparency. Each tier's
disc positions (frame-lab/final/roundels.json) and the art polygon go into assets/card-data.js for card.js.
"""
import argparse, glob, json, os
from PIL import Image

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
FINAL = os.path.join(REPO, "docs", "design", "art-direction", "frame-lab", "final")
OUT = os.path.join(REPO, "docs", "design", "art-direction", "mockups", "assets")
CARD = (560, 1000)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("art_root")
    ap.add_argument("--window", required=True, help="window.json from the art recipe (tools/art/glass-art/window.json)")
    a = ap.parse_args()
    spec = json.load(open(a.window))
    sx, (ox, oy) = spec["scale"], spec["origin"]
    box = (round(ox), round(oy), round(ox + 560 * sx), round(oy + 1000 * sx))
    os.makedirs(os.path.join(OUT, "art"), exist_ok=True)
    os.makedirs(os.path.join(OUT, "frames"), exist_ok=True)
    for path in sorted(glob.glob(os.path.join(a.art_root, "*", "*.png"))):
        run = os.path.basename(os.path.dirname(path))[-1]
        name = os.path.splitext(os.path.basename(path))[0]
        im = Image.open(path).convert("RGB")
        if im.size != tuple(spec["canvas"]):
            raise SystemExit(f"{path}: {im.size}, expected {spec['canvas']}; remake it, don't fit it")
        im.crop(box).resize(CARD, Image.LANCZOS).save(os.path.join(OUT, "art", f"{name}-{run}.jpg"), quality=86)
        print("art", name, run)
    for path in sorted(glob.glob(os.path.join(FINAL, "tier[1-6]-*.png"))):
        if path.endswith("-padded.png"):
            continue
        tier = os.path.basename(path)[4]
        Image.open(path).resize(CARD, Image.LANCZOS).save(os.path.join(OUT, "frames", f"tier{tier}.webp"), quality=92, method=6)
        print("frame", tier)
    roundels = json.load(open(os.path.join(FINAL, "roundels.json")))
    # One script file, so the pages also work opened straight from disk (no server, no fetch).
    data = {"note": "Generated by tools/art/mockups/prep_assets.py. roundels: frame-lab/final/roundels.json; art: the art recipe's window.json, card units (560 x 1000).",
            "roundels": roundels, "art": spec["art"]}
    open(os.path.join(OUT, "card-data.js"), "w").write("window.CARD_DATA = " + json.dumps(data, indent=1) + ";\n")

if __name__ == "__main__":
    main()
